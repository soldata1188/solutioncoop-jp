/**
 * ホームの最新情報。文章は支給された原文のままです（末尾のタグ行だけ外しています）。
 * カードを足すときは配列の先頭に足してください。外部へのリンクは付けません。
 * 写真があるカードは imageAlt を書き、public/news/{id}-320|480|640.avif と .webp を置きます。
 * 元画像の幅が 960px 以上のときだけ {id}-960.avif と .webp も置きます。引き伸ばしません。
 * 写真が無いカードは imageAlt を省くと、既存のロゴタイルになります。
 * カードに出す見出しは shortTitle。原文に無い事実を足した見出しは使いません。
 */
export type NewsItem = {
  /** ファイル名に使う識別子。公開URLには出しません */
  id: string;
  /** ISO 8601。表示は日本時間の YYYY.MM.DD */
  createdAt: string;
  /** 内容から読み取れるときだけ。無ければ出しません */
  label?: string;
  /** 任意。原文にある事実だけで短くした見出し */
  shortTitle?: string;
  /** 原文。カードの本文としては出しません */
  text: string;
  /** 写真の代替テキスト。見出しの繰り返しにはしません */
  imageAlt?: string;
  /** 省略時は 320/480/640/960。元画像が 960 未満なら 960 を入れない */
  imageWidths?: readonly number[];
};

export const NEWS_IMAGE_WIDTHS = [320, 480, 640, 960] as const;

/** カードに出す見出し。短い見出しが無いときは原文の最初の文です。 */
export function newsCardTitle(item: NewsItem): string {
  return item.shortTitle ?? item.text.split("\n")[0] ?? item.text;
}

export function newsSrcSet(item: { id: string; imageWidths?: readonly number[] }, ext: "avif" | "webp"): string {
  const widths = item.imageWidths ?? NEWS_IMAGE_WIDTHS;
  return widths.map((width) => `/news/${item.id}-${width}.${ext} ${width}w`).join(", ");
}

